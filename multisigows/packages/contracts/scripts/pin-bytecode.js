#!/usr/bin/env node
/**
 * Pins everything the app trusts about the contracts into packages/core/src/pinned.ts:
 *  - the runtime code hash of each contract (a vault is only a vault if its on-chain code
 *    hashes to the pinned proxy build),
 *  - the proxy's creation code (clients mine CREATE2 salts with it),
 *  - the byte ranges the factory's immutables occupy (so a deployed factory can be checked
 *    against the compiled template with those ranges masked out),
 *  - the recorded v2 deployments in packages/contracts/deployments/v2-<network>.json.
 *
 *   node scripts/pin-bytecode.js          write pinned.ts from the current artifacts
 *   node scripts/pin-bytecode.js --check  exit 1 if pinned.ts is stale (CI)
 */
const fs = require('node:fs');
const path = require('node:path');
const { keccak256, getAddress } = require('ethers');

const ROOT = path.resolve(__dirname, '..');
const OUT = path.resolve(ROOT, '../core/src/pinned.ts');
const DEPLOYMENTS_DIR = path.join(ROOT, 'deployments');

const PINNED = [
  { key: 'DarkSafeVaultV2', source: 'contracts/v2/DarkSafeVault.sol', name: 'DarkSafeVault' },
  { key: 'DarkSafeVaultProxyV2', source: 'contracts/v2/DarkSafeVaultProxy.sol', name: 'DarkSafeVaultProxy' },
  { key: 'DarkSafeVaultFactoryV2', source: 'contracts/v2/DarkSafeVaultFactory.sol', name: 'DarkSafeVaultFactory' },
];

function readArtifact(entry) {
  const file = path.join(ROOT, 'artifacts', entry.source, `${entry.name}.json`);
  if (!fs.existsSync(file)) throw new Error(`Missing artifact ${file}; run hardhat compile first.`);
  return JSON.parse(fs.readFileSync(file, 'utf8'));
}

/** Immutable byte ranges in the deployed code, from the build-info the artifact points at. */
function immutableRanges(entry) {
  const dbg = JSON.parse(fs.readFileSync(path.join(ROOT, 'artifacts', entry.source, `${entry.name}.dbg.json`), 'utf8'));
  const buildInfoPath = path.resolve(path.join(ROOT, 'artifacts', entry.source), dbg.buildInfo.replace(/\\/g, '/'));
  const buildInfo = JSON.parse(fs.readFileSync(buildInfoPath, 'utf8'));
  const refs = buildInfo.output.contracts[entry.source][entry.name].evm.deployedBytecode.immutableReferences || {};
  const ranges = Object.values(refs).flat().map((r) => ({ start: r.start, length: r.length }));
  return ranges.sort((a, b) => a.start - b.start);
}

const ADDRESS_RE = /^0x[0-9a-fA-F]{40}$/;
const HASH_RE = /^0x[0-9a-fA-F]{64}$/;

/** Reads deployments/v2-<network>.json records written by deploy-v2.mjs. */
function readDeployments(pinned) {
  if (!fs.existsSync(DEPLOYMENTS_DIR)) return [];
  const files = fs.readdirSync(DEPLOYMENTS_DIR).filter((f) => /^v2-(orchard|mainnet)\.json$/.test(f)).sort();
  return files.map((f) => {
    const rec = JSON.parse(fs.readFileSync(path.join(DEPLOYMENTS_DIR, f), 'utf8'));
    const problems = [];
    if (!Number.isInteger(rec.chainId)) problems.push('chainId');
    if (!ADDRESS_RE.test(rec.factory?.address ?? '')) problems.push('factory.address');
    if (!ADDRESS_RE.test(rec.implementation?.address ?? '')) problems.push('implementation.address');
    if (!Number.isInteger(rec.factory?.blockNumber)) problems.push('factory.blockNumber');
    if (!HASH_RE.test(rec.factory?.txHash ?? '')) problems.push('factory.txHash');
    if (problems.length) throw new Error(`${f}: missing or malformed ${problems.join(', ')}`);
    if (rec.implementationCodeHash !== pinned.DarkSafeVaultV2.runtimeCodeHash) {
      throw new Error(`${f}: its implementation code hash no longer matches the compiled DarkSafeVault`);
    }
    if (rec.proxyCodeHash !== pinned.DarkSafeVaultProxyV2.runtimeCodeHash) {
      throw new Error(`${f}: its proxy code hash no longer matches the compiled DarkSafeVaultProxy`);
    }
    return {
      chainId: rec.chainId,
      network: rec.network,
      factory: getAddress(rec.factory.address),
      implementation: getAddress(rec.implementation.address),
      factoryBlock: rec.factory.blockNumber,
      factoryTx: rec.factory.txHash,
    };
  });
}

function render() {
  const pinned = {};
  const lines = [
    '// GENERATED by packages/contracts/scripts/pin-bytecode.js from the Hardhat artifacts.',
    '// Do not edit by hand: run `pnpm -F @darksafe/contracts pin` after changing a contract.',
    '',
    'export interface PinnedContract {',
    '  /** keccak256 of the deployed runtime code, with any immutable ranges zeroed. */',
    '  runtimeCodeHash: string;',
    '  runtimeBytes: number;',
    '  /** keccak256 of the creation code without constructor arguments. */',
    '  creationCodeHash: string;',
    '  /** Byte ranges filled in at deployment; zero them in on-chain code before comparing hashes. */',
    '  immutableRanges: ReadonlyArray<{ readonly start: number; readonly length: number }>;',
    '}',
    '',
    'export const PINNED_CONTRACTS = {',
  ];
  let proxyArtifact = null;
  for (const entry of PINNED) {
    const art = readArtifact(entry);
    const ranges = immutableRanges(entry);
    const runtime = art.deployedBytecode;
    pinned[entry.key] = { runtimeCodeHash: keccak256(runtime) };
    if (entry.key === 'DarkSafeVaultProxyV2') proxyArtifact = art;
    lines.push(
      `  ${entry.key}: {`,
      `    runtimeCodeHash: '${keccak256(runtime)}',`,
      `    runtimeBytes: ${(runtime.length - 2) / 2},`,
      `    creationCodeHash: '${keccak256(art.bytecode)}',`,
      `    immutableRanges: [${ranges.map((r) => `{ start: ${r.start}, length: ${r.length} }`).join(', ')}],`,
      '  },'
    );
  }
  lines.push('} as const satisfies Record<string, PinnedContract>;', '');

  if (immutableRanges(PINNED[1]).length !== 0) {
    throw new Error('DarkSafeVaultProxy must not have immutables: vaults are recognised by one code hash.');
  }
  lines.push(
    '/** DarkSafeVaultProxy creation code (CREATE2 init code = this + abi.encode(implementation, initData)). */',
    `export const VAULT_PROXY_CREATION_CODE = '${proxyArtifact.bytecode}';`,
    '',
    '/** DarkSafeVaultProxy runtime code: every genuine v2 vault has exactly this code. */',
    `export const VAULT_PROXY_RUNTIME_CODE = '${proxyArtifact.deployedBytecode}';`,
    ''
  );

  const deployments = readDeployments(pinned);
  lines.push(
    'export interface VaultDeploymentRecord {',
    '  chainId: number;',
    '  network: string;',
    '  factory: string;',
    '  implementation: string;',
    '  /** Block that created the factory; nothing of ours exists before it. */',
    '  factoryBlock: number;',
    '  factoryTx: string;',
    '}',
    '',
    '/** v2 deployments recorded by scripts/deploy-v2.mjs (packages/contracts/deployments). */',
    'export const V2_DEPLOYMENTS: ReadonlyArray<VaultDeploymentRecord> = ['
  );
  for (const d of deployments) {
    lines.push(
      '  {',
      `    chainId: ${d.chainId},`,
      `    network: '${d.network}',`,
      `    factory: '${d.factory}',`,
      `    implementation: '${d.implementation}',`,
      `    factoryBlock: ${d.factoryBlock},`,
      `    factoryTx: '${d.factoryTx}',`,
      '  },'
    );
  }
  lines.push('];', '');
  return lines.join('\n');
}

const next = render();
if (process.argv.includes('--check')) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : '';
  if (current !== next) {
    console.error('packages/core/src/pinned.ts is stale: the compiled contracts or recorded deployments no longer match it.');
    console.error('Run `pnpm -F @darksafe/contracts pin` and review the diff.');
    process.exit(1);
  }
  console.log('pinned.ts matches the compiled artifacts and recorded deployments.');
} else {
  fs.writeFileSync(OUT, next);
  console.log(`Wrote ${path.relative(process.cwd(), OUT)}`);
}
